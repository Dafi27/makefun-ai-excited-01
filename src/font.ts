/** Pixel width of a string at a given integer scale, including spacing. */
export function textWidth(text: string, scale: number): number {
  if (text.length === 0) return 0;
  return text.length * GLYPH_ADVANCE * scale - scale;
}

/** Pixel height of one line of text at a given integer scale. */
export function textHeight(scale: number): number {
  return GLYPH_HEIGHT * scale;
}
